/**
 * Browser player for a stored WeChat voice note that is still SILK.
 * WeChat voice is 24000 Hz when the sample rate is absent, matching `silkRate`.
 * The page does not run speech recognition. Transcripts stay `voice_item.text`.
 */
export const HISTORY_SILK_RATE = 24_000;

/** Module script served at `/history/player.js`. It never sees the bridge token. */
export function historyPlayerSource(): string {
  return [
    'import { decode } from "/history/silk.js";',
    `const RATE = ${HISTORY_SILK_RATE};`,
    "function pcmToWav(pcm) {",
    "  const data = pcm.byteLength % 2 === 0 ? pcm : pcm.subarray(0, pcm.byteLength - 1);",
    "  const out = new Uint8Array(44 + data.byteLength);",
    "  const view = new DataView(out.buffer);",
    "  const ascii = (offset, text) => {",
    "    for (let i = 0; i < text.length; i += 1) out[offset + i] = text.charCodeAt(i);",
    "  };",
    '  ascii(0, "RIFF");',
    "  view.setUint32(4, 36 + data.byteLength, true);",
    '  ascii(8, "WAVE");',
    '  ascii(12, "fmt ");',
    "  view.setUint32(16, 16, true);",
    "  view.setUint16(20, 1, true);",
    "  view.setUint16(22, 1, true);",
    "  view.setUint32(24, RATE, true);",
    "  view.setUint32(28, RATE * 2, true);",
    "  view.setUint16(32, 2, true);",
    "  view.setUint16(34, 16, true);",
    '  ascii(36, "data");',
    "  view.setUint32(40, data.byteLength, true);",
    "  out.set(data, 44);",
    "  return out;",
    "}",
    "function silkSource(button) {",
    '  const src = button.getAttribute("data-silk");',
    '  if (!src || !/^\\/history\\/media\\/[0-9a-f]{32}$/.test(src)) return null;',
    "  return src;",
    "}",
    "async function play(button) {",
    '  if (button.dataset.busy === "1") return;',
    "  const src = silkSource(button);",
    "  if (!src) return;",
    '  button.dataset.busy = "1";',
    "  button.disabled = true;",
    "  try {",
    '    const response = await fetch(src, { credentials: "same-origin" });',
    '    if (!response.ok) throw new Error("unavailable");',
    "    const encoded = new Uint8Array(await response.arrayBuffer());",
    "    const decoded = await decode(encoded, RATE);",
    "    const wav = pcmToWav(decoded.data);",
    '    const url = URL.createObjectURL(new Blob([wav], { type: "audio/wav" }));',
    '    const audio = document.createElement("audio");',
    "    audio.controls = true;",
    '    audio.preload = "auto";',
    "    audio.src = url;",
    "    button.replaceWith(audio);",
    "    try {",
    "      await audio.play();",
    "    } catch {",
    "      /* The control stays usable when autoplay is blocked. */",
    "    }",
    "  } catch {",
    "    button.disabled = false;",
    '    button.dataset.busy = "0";',
    '    button.textContent = "Could not play";',
    "  }",
    "}",
    'document.addEventListener("click", (event) => {',
    "  const target = event.target;",
    "  if (!(target instanceof Element)) return;",
    '  const button = target.closest("button[data-silk]");',
    "  if (!(button instanceof HTMLButtonElement)) return;",
    "  event.preventDefault();",
    "  void play(button);",
    "});",
    "",
  ].join("\n");
}
